export function findHelpTopic(input: string): HelpTopic | null {
  const normalized = input.trim().toLowerCase().replace(/^\/+/, '')
  if (!normalized) return null
  return (
    ADMIN_HELP_TOPICS.find((topic) => topic.aliases.some((alias) => normalized === alias)) ??
    ADMIN_HELP_TOPICS.find((topic) => topic.aliases.some((alias) => normalized.includes(alias))) ??
    null
  )
}
